def normalize_kaggle_disease_name(name: str) -> str:
    normalized = normalize_text(name)
    return re.sub(r"\s+", " ", normalized)


def kaggle_symptom_slug(name: str) -> str:
    slug = normalize_text(name).strip("_")
    slug = re.sub(r"[\s\-]+", "_", slug)
    slug = re.sub(r"[^a-z0-9_]", "", slug)
    slug = re.sub(r"_+", "_", slug)
    return slug.strip("_")


def translate_kaggle_disease(name: str) -> str:
    key = normalize_kaggle_disease_name(name)
    return DISEASE_EN_TO_VI.get(key, name.strip())


def translate_kaggle_symptom(name: str) -> str:
    slug = kaggle_symptom_slug(name)
    return SYMPTOM_SLUG_TO_VI.get(slug, name.strip())
